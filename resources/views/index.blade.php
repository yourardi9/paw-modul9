            <p>
              Di era modern ini, kejujuran dan konsistensi dengan tindakan dan
              ucapan adalah sesuatu yang penting. Salah satu untuk mendapatkan
              sifat itu adalah dengan menerapkan prinsip integritas. Integritas
              adalah mutu, sifat, atau keadaan yang menunjukkan kesatuan yang
              utuh sehingga memiliki potensi dan kemampuan yang memancarkan
              kewibawaan atau kejujuran. Jadi, semua perbuatan dan perkataan
              yang dilakukan seseorang akan mencerminkan integritas orang
              tersebut. Oleh karena itu, kita perlu memiliki sebuah prinsip
              integritas agar mendapat kepercayaan orang lain, membangun
              reputasi, dan juga membangun karakter positif. Integritas adalah
              prinsip yang perlu dimiliki oleh semua orang, bahkan mahasiswa.
            </p>

            <p>
              Seperti yang disinggung oleh Rektor Telkom University, Prof. Dr.
              Adiwijaya pada EJLS bahwa seluruh mahasiswa perlu memiliki
              integritas. Terutama mahasiswa Telkom University. Meskipun Telkom
              University mempunyai banyak kampus yaitu Bandung, Jakarta dan
              Surabaya, tetapi semuanya harus memiliki integritas yang sama. Hal
              ini sangat penting karena integritas tidak hanya memengaruhi
              reputasi individu, tetapi juga berperan penting dalam kualitas
              pendidikan dan profiesionalisme di masa depan. Mahasiswa bisa
              menerapkan integritas dengan mengerjakan tugas dengan orisinal dan
              jujur, sehingga kompentensi yang mereka dapatkan adalah hasil dari
              usaha dan kemampuan sendiri. Dalam rangka memperkuat prinsip ini,
              Program Studi Sistem Informasi mengadakan kuliah tamu yang
              membahas tentang pentingnya integritas.
            </p>

            <p>
              Didalam kulliah tamu tersebut, dijelaskan bahwa integritas yang
              sangat penting ini dipengaruhi mempunyai 2 faktor. Faktor yang
              pertama adalah faktor internal. Faktor internal dalam integritas
              ini merupakan hal yang berasal dari dalam diri individu, misalnya
              nilai profesionalitas dan norma seseorang. Faktor internal ini
              menekankan pentingnya dedikasi terhadap etika. Faktor internal
              juga seringkali didorang oleh keyakinan agama dan prinsip moral
              yang kuat. Tetapi, integritas yang bergantung hanya pada faktor
              internal saja belum cukup. Selain faktor internal, terdapat juga
              faktor eksternal yang juga berperan penting dalam mendukung
              integritas suatu individu.
            </p>

            <p>
              Faktor eksternal juga memiliki peran penting untuk mendukung
              integritas individu. Dalam perkuliahan, faktor eksternal bisa
              meliputi sistem pengawasan dan peraturan yang diterapkan baik
              untuk mahasiswa maupun dosen. Misalnya, pada Telkom University
              Surabaya yang dilengkapi dengan CCTV yang bisa membantu mendeteksi
              penyalahgunaan fasilitas kampus. Tanpa adanya hukuman atau sanksi,
              mahasiswa diharapkan untuk mengembangkan integritas yang kuat di
              dalam diri mereka sendiri.
            </p>

            <p>
              Pada kuliah tamu, juga diberikan contoh nyata pentingnya faktor
              eksternal integritas. Contoh nyata tersebut terjadi di Univeristy
              Teknologi Mara, Malaysia. Di sana, pernah terjadi kejadian dosen
              menolak suap dari mahasiswa yang melanggar aturan. Mahasiswa ini
              diberi sanksi harus mengulang semester depan. Namun, mahasiswa ini
              malah ingin melakukan suap kepada dosen. Meskipun mahasiswa itu
              memiliki relasi dengan orang penting, dosen tersebut tetap
              berpegang teguh pada integritasnya karena adanya peraturan dan
              pengawasan yang ketat. Hal ini menunjukkan bahwa faktor internal
              seperti peraturan dan pengawasan bisa memperkuat integritas
              seseorang.
            </p>

            <p>
              Seperti yang dibahas pada kuliah tamu oleh Ainatul Fathiyah Abdul
              Rahim, integritas adalah prinsip yang harus dimiliki oleh
              mahasiswa Sistem Infomrasi untuk memastikan kualiatas pendidikan
              dan profesionalisme yang tinggi. Webinar kuliah tamu internasional
              tersebut menekankan pentingnya integritas bagi mahasiswa dan
              bagaimana faktor internal dan eksternal seperti peraturan bisa
              membantu membangun kepercayaan dan reputasi untuk masa depan.
            </p>

            <p>
